MODEL_OWN = "自社プロダクト"
MODEL_CONTRACTED = "受託・労働集約"
MODEL_REAL_ESTATE = "不動産"
MODEL_OTHER = "その他"


def _count(text: str, markers) -> int:
    return sum(1 for m in markers if m in text)


def classify_model(text: str) -> str:
    """事業モデルの多数決分類。除外系(受託・不動産)は保守的に、
    明確に上回った場合のみ判定する(誤除外より見逃しに倒す)。"""
    own = _count(text, OWN_PRODUCT_MARKERS)
    con = _count(text, CONTRACTED_MARKERS)
    re_ = _count(text, REAL_ESTATE_MARKERS)
    if con >= 2 and con > own:
        return MODEL_CONTRACTED
    if re_ >= 2 and re_ > own:
        return MODEL_REAL_ESTATE
    if own >= 1 and own >= max(con, re_):
        return MODEL_OWN
    return MODEL_OTHER


def match_themes(text: str) -> List[str]:
    """当たったテーマ名のリスト(キーワード2件以上、またはテーマ固有語1件で成立)。

    有報の長文では1語だけの偶然一致が起きやすいので、既定は2語以上。
    ただし「Z世代」「リユース」のような固有性の高い語は1件で成立とする。
    """
    strong = {"Z世代", "リユース", "インバウンド", "蓄電", "半導体", "介護",
              "インフルエンサー", "ロールアップ", "エネルギー自給"}
    out = []
    for theme, kws in THEMES.items():
        hits = [k for k in kws if k in text]
        if len(hits) >= 2 or any(k in strong for k in hits):
            out.append(theme)
    return out
